const fmt = (value) =>
  `\u20b9${Number(value || 0).toLocaleString("en-IN", {
    maximumFractionDigits: 0,
  })}`;

function addMessage(role, content, extraClass = "") {
  const messages = document.getElementById("messages");
  const row = document.createElement("div");
  row.className = `message ${role}`;
  row.innerHTML = `<div class="avatar">${
    role === "user" ? "You" : "AI"
  }</div><div class="bubble ${extraClass}">${content}</div>`;
  messages.appendChild(row);
  messages.scrollTop = messages.scrollHeight;
  return row.querySelector(".bubble");
}

function showToast(message) {
  const stack = document.getElementById("toasts");
  const toast = document.createElement("div");
  toast.className = "toast";
  toast.textContent = message;
  stack.appendChild(toast);
  setTimeout(() => toast.remove(), 3600);
}

function addChip(text) {
  const strip = document.getElementById("toolStrip");
  const chip = document.createElement("span");
  chip.className = "chip";
  chip.textContent = text;
  strip.prepend(chip);
  while (strip.children.length > 5) strip.lastElementChild.remove();
}

function switchTab(tabName) {
  document.querySelectorAll(".tab-btn").forEach((button) => {
    button.classList.toggle("active", button.dataset.tab === tabName);
  });
  document.querySelectorAll(".tab-panel").forEach((panel) => {
    panel.classList.toggle("active", panel.id === `tab-${tabName}`);
  });
  document.querySelectorAll("[data-tab-jump]").forEach((button) => {
    button.classList.toggle("active", button.dataset.tabJump === tabName);
  });
  renderChartsForActiveTab();
}

function activeTabName() {
  return (
    document.querySelector(".tab-panel.active")?.id?.replace("tab-", "") ||
    "chat"
  );
}

function renderChartsForActiveTab() {
  if (!AppState.dashboard) return;
  const tab = activeTabName();
  window.requestAnimationFrame(() => {
    if (tab === "dashboard") {
      drawCategoryChart(
        AppState.dashboard.analytics.category_breakdown,
        "categoryChart"
      );
    }
    if (tab === "analytics") {
      drawCategoryChart(
        AppState.dashboard.analytics.category_breakdown,
        "categoryChartLarge"
      );
    }
  });
}

function transactionMarkup(txn) {
  return `
    <div class="txn">
      <strong>${txn.recipient} · ${fmt(txn.amount)}</strong>
      <span>${txn.status} · <b class="risk-${txn.risk_level}">${
    txn.risk_level
  } risk</b> · ${txn.method}</span>
    </div>
  `;
}

function approvalMarkup(item) {
  return `
    <div class="approval-item">
      <strong>${item.recipient} · ${fmt(item.amount)}</strong>
      <span>${item.transaction_id} · ${item.reason}</span>
      <div class="approval-actions">
        <button class="ghost-btn approval-decision" data-id="${
          item.id
        }" data-decision="rejected">Reject</button>
        <button class="primary-btn approval-decision" data-id="${
          item.id
        }" data-decision="approved">Approve</button>
      </div>
    </div>
  `;
}

