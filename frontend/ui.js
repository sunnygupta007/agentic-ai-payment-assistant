function addInvoice(payload) {
  const invoice = {
    invoice_id: payload.invoice_id,
    client: payload.client || "Demo Client",
    amount: Number(payload.amount || 0),
    description:
      payload.description || "Demo invoice generated by AI assistant",
    status: payload.status || "generated",
    created_at: payload.created_at || new Date().toISOString(),
    note: payload.note || "This is a simulated invoice for demo purposes only.",
  };

  const existingInvoices = Array.isArray(AppState.invoices)
    ? AppState.invoices
    : [];

  AppState.invoices = [
    invoice,
    ...existingInvoices.filter(
      (item) => item.invoice_id !== invoice.invoice_id
    ),
  ];

  AppState.selectedInvoiceId = invoice.invoice_id;

  saveInvoices();
  renderInvoices();
}

function selectedInvoice() {
  return (
    AppState.invoices.find(
      (item) => item.invoice_id === AppState.selectedInvoiceId
    ) || AppState.invoices[0]
  );
}

function renderInvoices() {
  const list = document.getElementById("invoiceList");
  const preview = document.getElementById("invoicePreview");
  if (!list || !preview) return;

  const invoices = Array.isArray(AppState?.invoices) ? AppState.invoices : [];
  if (!invoices.length) {
    list.innerHTML = `<div class="invoice-empty"><strong>No invoices yet</strong><span>Generate one from chat, for example: Generate invoice for INR 3500 to Acme Labs.</span></div>`;
    preview.innerHTML = `<div class="invoice-paper empty-preview"><strong>Invoice preview</strong><span>Your next simulated invoice will appear here.</span></div>`;
    return;
  }

  const active = selectedInvoice();
  AppState.selectedInvoiceId = active.invoice_id;
  list.innerHTML = AppState.invoices
    .map(
      (invoice) => `
    <div class="invoice-card ${
      invoice.invoice_id === active.invoice_id ? "active" : ""
    }">
      <div>
        <strong>${invoice.invoice_id}</strong>
        <span>${invoice.client} · ${fmt(invoice.amount)} · ${
        invoice.status
      }</span>
      </div>
      <div class="invoice-actions">
        <button class="ghost-btn invoice-preview-btn" data-invoice-id="${
          invoice.invoice_id
        }">Preview</button>
        <button class="ghost-btn invoice-copy-btn" data-invoice-id="${
          invoice.invoice_id
        }">Copy ID</button>
        <button class="primary-btn invoice-sent-btn" data-invoice-id="${
          invoice.invoice_id
        }">Mark Sent</button>
      </div>
    </div>
  `
    )
    .join("");

  preview.innerHTML = `
    <div class="invoice-paper">
      <div class="invoice-paper-head">
        <div><span>Demo Invoice</span><strong>${
          active.invoice_id
        }</strong></div>
        <em>${active.status}</em>
      </div>
      <div class="invoice-meta">
        <span>Bill to</span>
        <strong>${active.client}</strong>
        <span>Created</span>
        <strong>${new Date(active.created_at).toLocaleString()}</strong>
      </div>
      <div class="invoice-line">
        <span>${active.description}</span>
        <strong>${fmt(active.amount)}</strong>
      </div>
      <div class="invoice-total">
        <span>Total due</span>
        <strong>${fmt(active.amount)}</strong>
      </div>
      <p>${active.note}</p>
      <small>No real invoice, tax document, or payment request was issued.</small>
    </div>
  `;
  bindInvoiceButtons();
}

function bindInvoiceButtons() {
  document.querySelectorAll(".invoice-preview-btn").forEach((button) => {
    button.addEventListener("click", () => {
      AppState.selectedInvoiceId = button.dataset.invoiceId;
      renderInvoices();
    });
  });
  document.querySelectorAll(".invoice-copy-btn").forEach((button) => {
    button.addEventListener("click", async () => {
      await navigator.clipboard?.writeText(button.dataset.invoiceId);
      showToast(`Copied ${button.dataset.invoiceId}`);
    });
  });
  document.querySelectorAll(".invoice-sent-btn").forEach((button) => {
    button.addEventListener("click", () => {
      AppState.invoices = AppState.invoices.map((invoice) =>
        invoice.invoice_id === button.dataset.invoiceId
          ? { ...invoice, status: "sent" }
          : invoice
      );
      saveInvoices();
      renderInvoices();
      showToast("Invoice marked sent in demo mode");
    });
  });
}

function bindApprovalButtons() {
  document.querySelectorAll(".approval-decision").forEach((button) => {
    button.addEventListener("click", async () => {
      await API.decideApproval(button.dataset.id, button.dataset.decision);
      showToast(`Approval ${button.dataset.decision}`);
      await refreshDashboard();
    });
  });
}

function addApprovalQueueCard(payload) {
  const amount = fmt(payload.amount || 0);
  const recipient = payload.recipient || "Unknown recipient";
  const reason = payload.reason || "Risk policy triggered.";
  const bubble = addMessage(
    "assistant",
    `<strong>This simulated payment was paused and added to the approval queue.</strong><span>${amount} to ${recipient}. ${reason}</span><button class="queue-link" data-tab-target="approvals">View in Approvals</button>`,
    "approval-card"
  );
  const link = bubble.querySelector("[data-tab-target]");
  if (link) {
    link.addEventListener("click", () => switchTab("approvals"));
  }
}

