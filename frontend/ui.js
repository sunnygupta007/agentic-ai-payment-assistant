function renderDashboard(data) {
  AppState.dashboard = data || {};

  const wallet = data?.wallet || {};
  const analytics = data?.analytics || {};

  const approvals = Array.isArray(data?.approvals) ? data.approvals : [];

  const transactions = Array.isArray(data?.transactions)
    ? data.transactions
    : [];

  const logs = Array.isArray(data?.logs) ? data.logs : [];

  const recommendations = Array.isArray(analytics?.recommendations)
    ? analytics.recommendations
    : [];

  const fraudInsights = Array.isArray(analytics?.fraud_insights)
    ? analytics.fraud_insights
    : [];

  document.getElementById("walletBalance").textContent = fmt(wallet.balance);

  document.getElementById("chatWalletBalance").textContent = fmt(
    wallet.balance
  );

  document.getElementById("walletMini").textContent = fmt(wallet.balance);

  document.getElementById("walletCurrency").textContent =
    wallet.currency || "INR";

  document.getElementById("monthlySpend").textContent = fmt(
    analytics.total_spend
  );

  document.getElementById("approvalCount").textContent = approvals.length;

  document.getElementById("chatApprovalCount").textContent = approvals.length;

  document.getElementById("approvalPanelCount").textContent = approvals.length;

  document.getElementById("txnCount").textContent = transactions.length;

  const emptyApprovals = `
    <div class="approval-item">
      <strong>No pending approvals</strong>
      <span>Risky simulated transfers will appear here.</span>
    </div>
  `;

  document.getElementById("approvalList").innerHTML = approvals.length
    ? approvals.map(approvalMarkup).join("")
    : emptyApprovals;

  document.getElementById("approvalListFull").innerHTML = approvals.length
    ? approvals.map(approvalMarkup).join("")
    : emptyApprovals;

  const emptyTransactions = `
    <div class="txn">
      <strong>No transactions yet</strong>
      <span>Simulated payments will appear here.</span>
    </div>
  `;

  document.getElementById("transactions").innerHTML = transactions.length
    ? transactions.map(transactionMarkup).join("")
    : emptyTransactions;

  document.getElementById("transactionsFull").innerHTML = transactions.length
    ? transactions.map(transactionMarkup).join("")
    : emptyTransactions;

  document.getElementById("activityLog").innerHTML = logs.length
    ? logs
        .map(
          (log) => `
            <div class="log-row">
              <strong>${String(log.type || "").replaceAll("_", " ")}</strong>
              <span>${log.message || ""}</span>
            </div>
          `
        )
        .join("")
    : `
        <div class="log-row">
          <strong>No activity yet</strong>
          <span>Agent and audit events will appear here.</span>
        </div>
      `;

  document.getElementById("recommendations").innerHTML = recommendations.length
    ? recommendations
        .map(
          (item) => `
            <div class="recommendation">
              <strong>Recommendation</strong>
              <span>${item}</span>
            </div>
          `
        )
        .join("")
    : `
        <div class="recommendation">
          <strong>No recommendations</strong>
          <span>AI insights will appear here.</span>
        </div>
      `;

  document.getElementById("fraudInsights").innerHTML = fraudInsights.length
    ? fraudInsights
        .map(
          (item) => `
            <div class="txn">
              <strong>${item.recipient}</strong>
              <span>
                ${item.transaction_id}
                ·
                <b class="risk-${item.risk_level}">
                  ${item.risk_level} risk
                </b>
              </span>
            </div>
          `
        )
        .join("")
    : `
        <div class="txn">
          <strong>No active fraud insights</strong>
          <span>High-risk simulated transfers will appear here.</span>
        </div>
      `;

  bindApprovalButtons();
  renderInvoices();
  renderChartsForActiveTab();

  AppState.currentApproval = approvals.length > 0 ? approvals[0] : null;
}

function openTopUpModal(amount = "") {
  const modal = document.getElementById("topUpModal");
  document.getElementById("topUpAmount").value = amount;
  document.querySelectorAll(".preset-btn").forEach((button) => {
    button.classList.toggle("active", button.dataset.amount === String(amount));
  });
  if (!modal.open) modal.showModal();
}

async function submitTopUp(amount, source = "ui") {
  const numeric = Number(amount);
  if (!Number.isFinite(numeric) || numeric <= 0) {
    showToast("Enter a valid top-up amount");
    return;
  }
  await API.topUpWallet(AppState.sessionId, numeric, source);
  document.getElementById("topUpModal").close();
  showToast(`Added ${fmt(numeric)} to demo wallet`);
  await refreshDashboard();
}

async function refreshDashboard() {
  const data = await API.dashboard(AppState.sessionId);
  renderDashboard(data);
}
